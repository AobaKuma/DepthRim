# -*- coding: utf-8 -*-
import io
p = 'Docs/箱網養殖_內容設計.md'
s = io.open(p, encoding='utf-8').read()
start = s.index('### 6.1 風暴與破網')
end = s.index('### 6.2 掠食者')
new = u'''### 6.1 風暴與破網

**外海**：浮框在水面上，會吃到現有的海況傷害：`MapComponent_SeaWeather.BatterBuildings` 對靠海建築**平均**每 8 小時（惡劣海況）或 3 小時（暴風雨）打 3～8／6～15 點，**不會低於最大 HP 的 20%**。箱網不另外吃一份傷害，直接用這套。

| HP 區間（外海） | 狀態 | 後果 |
|---|---|---|
| > 50% | 完好 | 無 |
| 20～50% | 破損 | 每次海況傷害結算時，額外 5% 機率「破網」（損失 5～15% 的魚、生成逃逸魚，§6.6）；沒有風暴時，每日另有 2% 機率破網（掠食者咬的洞沒補） |
| < 20%（海況傷害的下限） | 危險 | 上述機率提高到 15%；每日再 5% 機率損失 3% 的魚 |

**灣內**：`MapComponent_SeaWeather` 只在海面地圖跑，所以灣內**沒有海況傷害**、浮框不會被浪打壞。原版天氣（大雨、雷雨、強風）只造成：

| 天氣條件 | 效果 |
|---|---|
| `windSpeedFactor ≥ 1.2` 或 `rainRate ≥ 0.5` | 溶氧 −0.08（岸上逕流、濁度）；成長 ×0.8 |
| 連續 2 天以上 | 藻華機率提高（§6.3） |
| 網況 < 50% | 每日 1% 機率破網（沒有海況的 5%／15% 追加；掠食者仍會咬） |

- 修網：15 布＋10 鋼、400 工作，恢復 60 HP（不超過上限）。
- 換網：25 布、600 工作，恢復到 100%（HP 全滿）；網況 < 50% 時才可用。
- 外海的風暴成長懲罰見 §5.3；灣內只有原版天氣造成的 ×0.8。
- 玩家可以在風暴前「緊急收成」止損：見 §7。灣內沒有破網壓力，通常可以等到可收成再收。

'''
s = s[:start] + new + s[end:]
io.open(p, 'w', encoding='utf-8').write(s)
print('replaced', len(new))
