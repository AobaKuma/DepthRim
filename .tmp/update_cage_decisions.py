# -*- coding: utf-8 -*-
import io
p = 'Docs/箱網養殖_內容設計.md'
s = io.open(p, encoding='utf-8').read()
start = s.index('## 17. 待決事項')
end = s.index('## 18. 明確不做的事')
new = u'''## 17. 待決事項

1. **灣內與外海要不要拆成兩種箱網 Def？** 本稿建議共用：同一個 `DepthRim_NetCage_Shallow` 靠 `PlaceWorker` 判斷場地，只有水溫、天氣、可養品種不同。拆成兩個 Def 的好處是成本與貼圖可以分開調；壞處是重複。
2. **灣內水深要不要固定 10／50 m？** 原版地形沒有水深資料；固定值是設計妥協。如果之後有 `TerrainDef` 的水深欄位，再改成讀地形。
3. **灣內天氣只做「溶氧 −0.08、成長 ×0.8、不破網」夠不夠？** 這樣灣內是低風險入門，但可能太安全。要不要加「連續大雨造成一次小規模破網」？
4. **船能不能當箱網的補給基地或電源？** 本稿說船只運貨、不算連通、不供電；如果讓船供電，箱網就會依賴一艘會離開的船。跨層電力（§4.9 M5.5）目前是給吊架↔鐘、柱腳↔柱頂，不建议用在箱網。
5. **沒有水面戰鬥的前提下，偷魚要不要做？** 本稿建議第一版不做；M3 再從「夜間剪網」「岸上偷魚」「不做」三選一。
6. **外海箱網的門檻是船還是研究？** 本稿建議船就是門檻，不另開研究；如果覺得太快，可以把外海表層網掛在 `DepthRim_CoastalShipbuilding` 的解鎖清單裡。
7. **網層數量**：三種（表層／斜溫／深層）還是先做兩種（表層／深層）？三種的內容成本主要在貼圖與平衡。
8. **魚苗來源**：魚苗網＋貿易，還是只能貿易？魚苗網讓玩家可以自力更生，但多一個建築。
9. **密度控制**：固定 `stockCount` 還是給滑桿？固定數量決策乾淨，但玩家少一個「微調」的樂趣。
10. **箱網要不要吃通用海況傷害（只外海）**：本稿說要（沿用現有系統），但 20% 下限讓箱網永遠不會被風暴打爛，只能打到「一直破網」。要不要改成箱網專屬的風暴判定？
11. **掠食者**：只做海獺，還是連睡鯊一起做？海獺可愛、成本低；睡鯊需要新的 Pawn 與 AI。
12. **收成產物**：直接用 Odyssey 魚獲，還是新增「養殖魚」物品（可標示養殖來源、價格不同）？直接用最省，但少了「這是養的」的感覺。
13. **選育**：要不要做長期的品種升級？這會讓箱網從「現金支線」變成「長期經營」，但需要額外存檔與 UI。
14. **要不要獨立研究分頁**：目前掛在水下分頁；如果內容變多，可以考慮獨立「水產」分頁。
15. **數值**：這份文件的所有數字都是初值，必須實際玩過一輪（至少 3 個養殖季）再定。

'''
s = s[:start] + new + s[end:]
io.open(p, 'w', encoding='utf-8').write(s)
print('replaced', len(new))
